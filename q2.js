let n1= Number(prompt("Digite o primeiro número:"));
let n2= Number(prompt("Digite o segundo número:"));
 let soma= n1 + n2;
 let subt= n1 - n2;
 let multi= n1 * n2;
 let div= n1/n2;
 let resto= n1%n2;
 let pont= n1**n2;

 alert(
   "Soma:" + soma +
   "\nSubtração:" + subt +
   "\nMultiplicação:" + multi +
   "\nDivisão:" + div +
   "\nResto:" + resto +
   "\nPotencia:" + pont 
 );